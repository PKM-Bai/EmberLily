/**
 * Runs the real JNI/mGBA core with scripts/create_smoke_rom.py's original cartridge.
 * Before running, push .local/smoke.gba to the target app's external files directory:
 * /sdcard/Android/data/com.emberlily.app/files/smoke.gba.
 * A missing cartridge is a test failure, never a skipped compatibility result.
 * All cores and temporary branch files belong to this test; no user save is opened.
 */
@RunWith(AndroidJUnit4::class)
class NativeCoreSmokeTest {
    private lateinit var owner: ExecutorService
    private lateinit var directory: File
    private lateinit var rom: File
    private val handles = linkedSetOf<Long>()

    @Before
    fun prepareOriginalCartridge() {
        val context = InstrumentationRegistry.getInstrumentation().targetContext
        val external = requireNotNull(context.getExternalFilesDir(null)) { "External app files directory is unavailable" }
        val supplied = File(external, "smoke.gba")
        require(supplied.isFile) {
            "Required original diagnostic is missing: ${supplied.absolutePath}. " +
                "Run scripts/create_smoke_rom.py and adb push .local/smoke.gba to this path."
        }
        val bytes = supplied.readBytes()
        require(bytes.size >= 32768 && String(bytes, 0xA0, 12, Charsets.US_ASCII) == "EMBERTEST   " &&
            String(bytes, 0xAC, 4, Charsets.US_ASCII) == "ELTY") {
            "smoke.gba must be the original diagnostic generated by scripts/create_smoke_rom.py"
        }
        require(headerChecksum(bytes) == (bytes[0xBD].toInt() and 0xFF)) { "Diagnostic header checksum is invalid" }
        directory = File(context.cacheDir, "native-core-smoke-${UUID.randomUUID()}").canonicalFile
        check(directory.mkdir()) { "Cannot create private test directory" }
        rom = File(directory, "smoke.gba").apply { writeBytes(bytes) }
        owner = Executors.newSingleThreadExecutor { task -> Thread(task, "native-core-smoke-owner") }
    }

    @After
    fun closeOwnedCoresAndFiles() {
        try {
            if (::owner.isInitialized) onCore {
                // A failed assertion still closes every successfully opened native handle.
                var firstFailure: Throwable? = null
                for (handle in handles.toList()) {
                    try {
                        close(handle)
                    } catch (failure: Throwable) {
                        if (firstFailure == null) firstFailure = failure
                    }
                }
                firstFailure?.let { throw it }
            }
        } finally {
            if (::owner.isInitialized) owner.shutdownNow()
            if (::directory.isInitialized) directory.deleteRecursively()
        }
    }

    @Test
    fun rendersInputAndAudioRestoresCounterAndRejectsClosedHandles() = onCore {
        assertTrue("mGBA version must be available", NativeCore.coreVersion().isNotBlank())
        val main = SessionStore(File(directory, "sessions")).main(sha256(rom))
        val handle = open(rom, main)
        val pixels = IntArray(WIDTH * HEIGHT)
        assertFalse("No frame exists immediately after open", NativeCore.copyFrame(handle, pixels))

        val sound = advance(handle, 16)
        assertTrue("The diagnostic tone must yield stereo PCM samples", sound.shorts > 0)
        assertTrue("The diagnostic tone must contain nonzero audio", sound.nonzero)
        assertFrame(handle, pixels, IDLE_ARGB)
        val firstCounter = counter(handle)
        assertTrue("Diagnostic loop must increment EWRAM", firstCounter > 0)
        val registers = NativeCore.readVideoRegisters(handle)
        assertEquals(0x60, registers.size)
        val displayControl = (registers[0].toInt() and 255) or ((registers[1].toInt() and 255) shl 8)
        assertEquals("Diagnostic uses GBA bitmap mode 3", 3, displayControl and 7)
        registers.fill(0)
        assertEquals(displayControl and 255, NativeCore.readVideoRegisters(handle)[0].toInt() and 255)
        assertEquals("Video sampling must not advance execution", firstCounter, counter(handle))
        assertEquals("Released A is active-low 1", 1, keys(handle) and 1)

        advance(handle, 12, A)
        assertFrame(handle, pixels, A_ARGB)
        assertEquals("Pressed A is active-low 0", 0, keys(handle) and 1)
        assertTrue(counter(handle) > firstCounter)

        advance(handle, 12)
        assertFrame(handle, pixels, IDLE_ARGB)
        assertEquals(1, keys(handle) and 1)
        val savedCounter = counter(handle)
        assertTrue("Save must include a usable native state", NativeCore.saveState(handle, main.stateFile.absolutePath))
        assertTrue(main.stateFile.length() > 32)
        assertEquals("Saving must not advance the game", savedCounter, counter(handle))
        assertBatteryCounter(main.saveFile, savedCounter)
        advance(handle, 12)
        val laterCounter = counter(handle)
        assertTrue(laterCounter > savedCounter)
        val advancedState = File(main.directory, "advanced.state")
        assertTrue(NativeCore.saveState(handle, advancedState.absolutePath))
        assertBatteryCounter(main.saveFile, laterCounter)
        assertNotEquals(savedCounter and 0xFF, laterCounter and 0xFF)
        assertTrue("Restore must succeed for the same ROM", NativeCore.loadState(handle, main.stateFile.absolutePath))
        assertEquals("Restore must roll EWRAM back", savedCounter, counter(handle))
        assertBatteryCounter(main.saveFile, savedCounter)
        assertFalse("Restore invalidates the old framebuffer", NativeCore.copyFrame(handle, pixels))
        advance(handle, 12)
        assertFrame(handle, pixels, IDLE_ARGB)

        close(handle)
        NativeCore.close(handle) // The JNI contract makes repeated close harmless.
        expectClosed { NativeCore.runFrame(handle, 0) }
        expectClosed { NativeCore.copyFrame(handle, pixels) }
        expectClosed { NativeCore.drainAudio(handle, ShortArray(4096)) }
        expectClosed { NativeCore.readMemory(handle, COUNTER_ADDRESS, 4) }
        expectClosed { NativeCore.readVideoRegisters(handle) }
        expectClosed { NativeCore.saveState(handle, main.stateFile.absolutePath) }
        expectClosed { NativeCore.loadState(handle, main.stateFile.absolutePath) }
        expectClosed { NativeCore.readMemory(Long.MAX_VALUE, COUNTER_ADDRESS, 4) }
    }

    @Test
    fun rejectsTruncatedAndDifferentRomStatesWithoutChangingCurrentState() = onCore {
        val store = SessionStore(File(directory, "sessions"))
        val main = store.main(sha256(rom))
        val handle = open(rom, main)
        advance(handle, 16)
        assertTrue(NativeCore.saveState(handle, main.stateFile.absolutePath))
        val initialRam = NativeCore.readMemory(handle, COUNTER_ADDRESS, 8)
        val initialFiles = fileHashes(main.directory)
        val initialRomHash = sha256(rom)
        assertOpenRejected(rom.absolutePath, main.saveFile.absolutePath)
        assertOpenRejected(rom.absolutePath, rom.absolutePath)
        assertFalse("A state must not overwrite its ROM", NativeCore.saveState(handle, rom.absolutePath))
        assertFalse("A state must not overwrite the battery save", NativeCore.saveState(handle, main.saveFile.absolutePath))
        assertRejectedWithoutMutation(handle, main, rom)
        assertRejectedWithoutMutation(handle, main, main.saveFile)
        assertArrayEquals(initialRam, NativeCore.readMemory(handle, COUNTER_ADDRESS, 8))
        assertEquals(initialFiles, fileHashes(main.directory))
        assertEquals(initialRomHash, sha256(rom))

        val truncated = File(directory, "truncated.state").apply {
            val complete = main.stateFile.readBytes()
            writeBytes(complete.copyOf(complete.size - 1))
        }
        val corrupted = File(directory, "corrupted.state").apply {
            // Keep the header/size unchanged but alter a payload byte without
            // recomputing the stored checksum, as with disk corruption.
            val complete = main.stateFile.readBytes()
            complete[complete.lastIndex] = (complete.last().toInt() xor 1).toByte()
            writeBytes(complete)
        }
        advance(handle, 12)
        assertRejectedWithoutMutation(handle, main, truncated)
        assertRejectedWithoutMutation(handle, main, corrupted)

        // Change only the diagnostic's game code and repair its header checksum.
        // Both cartridges still execute identical code, but their ROM identity differs.
        val differentRom = File(directory, "different-smoke.gba").apply {
            val bytes = rom.readBytes()
            bytes[0xAF] = 'Z'.code.toByte()
            bytes[0xBD] = headerChecksum(bytes).toByte()
            writeBytes(bytes)
        }
        assertNotEquals(sha256(rom), sha256(differentRom))
        val other = store.main(sha256(differentRom))
        val otherHandle = open(differentRom, other)
        advance(otherHandle, 8)
        assertTrue(NativeCore.saveState(otherHandle, other.stateFile.absolutePath))
        close(otherHandle)
        assertRejectedWithoutMutation(handle, main, other.stateFile)
        assertTrue("The core must remain usable after rejected states", NativeCore.saveState(handle, main.stateFile.absolutePath))
        val before = counter(handle)
        advance(handle, 12)
        assertTrue(counter(handle) > before)
    }

    @Test
    fun forkRestoresAndAdvancesWithoutChangingAnySourceSessionFile() = onCore {
        val store = SessionStore(File(directory, "sessions"))
        val main = store.main(sha256(rom))
        val sourceHandle = open(rom, main)
        advance(sourceHandle, 16)
        val sourceCounter = counter(sourceHandle)
        assertTrue(NativeCore.saveState(sourceHandle, main.stateFile.absolutePath))
        close(sourceHandle) // No source core can mutate files while SessionStore copies them.
        assertBatteryCounter(main.saveFile, sourceCounter)
        val originalFiles = fileHashes(main.directory)
        val originalRomHash = sha256(rom)
        assertTrue(originalFiles.containsKey("battery.sav"))
        assertTrue(originalFiles.containsKey("resume.state"))

        val experiment = store.fork(main, "Native smoke experiment")
        assertNotEquals(main.directory.canonicalPath, experiment.directory.canonicalPath)
        assertEquals(sha256(main.stateFile), sha256(experiment.stateFile))
        assertEquals(sha256(main.saveFile), sha256(experiment.saveFile))
        assertEquals(originalFiles, fileHashes(main.directory))

        val branchHandle = open(rom, experiment)
        assertTrue(NativeCore.loadState(branchHandle, experiment.stateFile.absolutePath))
        assertEquals(sourceCounter, counter(branchHandle))
        advance(branchHandle, 16, A)
        val branchCounter = counter(branchHandle)
        assertTrue(branchCounter > sourceCounter)
        assertTrue(NativeCore.saveState(branchHandle, experiment.stateFile.absolutePath))
        assertEquals(branchCounter, counter(branchHandle))
        close(branchHandle)

        assertBatteryCounter(experiment.saveFile, branchCounter)
        assertBatteryCounter(main.saveFile, sourceCounter)
        assertNotEquals("The experiment must actually write different SRAM", sourceCounter and 0xFF, branchCounter and 0xFF)
        assertNotEquals(sha256(main.saveFile), sha256(experiment.saveFile))
        assertNotEquals("Branch state must actually change", sha256(main.stateFile), sha256(experiment.stateFile))
        assertEquals("Branch play/save/close must preserve every source file", originalFiles, fileHashes(main.directory))
        assertEquals("The source ROM must never change", originalRomHash, sha256(rom))
        assertEquals(2, store.list(main.romSha256).size)
    }

    @Test
    fun rejectsRomAndSavePathsOwnedByOtherLiveCores() = onCore {
        val main = SessionStore(File(directory, "source-session")).main(sha256(rom))
        val otherRom = File(directory, "other-smoke.gba").apply { writeBytes(rom.readBytes()) }
        val other = SessionStore(File(directory, "other-session")).main(sha256(otherRom))

        // Make the battery file a valid diagnostic input before opening its
        // owner. This proves that the reverse conflict is rejected because it
        // is an active save, rather than merely because saves are usually not ROMs.
        main.saveFile.writeBytes(rom.readBytes())
        val probeSave = File(directory, "probe.sav")
        val probe = NativeCore.open(main.saveFile.absolutePath, probeSave.absolutePath)
        if (probe != 0L) handles += probe
        assertTrue("The reverse-conflict fixture must be a loadable ROM", probe != 0L)
        close(probe)

        val sourceHandle = open(rom, main)
        val otherHandle = open(otherRom, other)
        val sourceRam = NativeCore.readMemory(sourceHandle, COUNTER_ADDRESS, 256 * 1024)
        val otherRam = NativeCore.readMemory(otherHandle, COUNTER_ADDRESS, 256 * 1024)
        val originalFiles = fileHashes(directory)
        val unusedSave = File(directory, "must-not-be-created.sav")

        assertOpenRejected(otherRom.absolutePath, rom.absolutePath)
        assertOpenRejected(rom.absolutePath, otherRom.absolutePath)
        assertOpenRejected(main.saveFile.absolutePath, unusedSave.absolutePath)
        assertFalse("Rejected open must not create a new save", unusedSave.exists())
        assertArrayEquals(sourceRam, NativeCore.readMemory(sourceHandle, COUNTER_ADDRESS, 256 * 1024))
        assertArrayEquals(otherRam, NativeCore.readMemory(otherHandle, COUNTER_ADDRESS, 256 * 1024))
        assertEquals("Rejected cross-core paths must preserve every ROM/save file", originalFiles, fileHashes(directory))

        advance(sourceHandle, 16)
        advance(otherHandle, 16)
        assertTrue("The source core must remain usable", NativeCore.saveState(sourceHandle, main.stateFile.absolutePath))
        assertTrue("The other core must remain usable", NativeCore.saveState(otherHandle, other.stateFile.absolutePath))
    }

    @Test
    fun bindsVersionTwoStatesToTheWholeRomAndCoreIdentity() = onCore {
        val main = SessionStore(File(directory, "sessions")).main(sha256(rom))
        val handle = open(rom, main)
        advance(handle, 16)
        assertTrue(NativeCore.saveState(handle, main.stateFile.absolutePath))
        val complete = main.stateFile.readBytes()
        assertTrue("Version two requires a 128-byte header plus core state", complete.size > 128)
        assertEquals("ELSTATE2", String(complete, 0, 8, Charsets.US_ASCII))
        assertEquals(2L, unsignedWord(complete.copyOfRange(28, 32)))
        assertEquals("Identity includes the source file length", rom.length(), unsignedWord(complete.copyOfRange(20, 24)))
        assertArrayEquals(
            "Native SHA-256 must match an independent digest of the complete input file",
            MessageDigest.getInstance("SHA-256").digest(rom.readBytes()),
            complete.copyOfRange(32, 64),
        )
        val coreIdentity = String(complete, 64, 64, Charsets.US_ASCII).substringBefore('\u0000')
        assertEquals("mGBA/${NativeCore.coreVersion()};26b7884bc25a5933960f3cdcd98bac1ae14d42e2", coreIdentity)

        val tampered = listOf(
            "rom-sha" to 32,
            "core-identity" to 64,
            "format-version" to 28,
        ).map { (label, offset) ->
            File(directory, "wrong-$label.state").apply {
                val bytes = complete.copyOf()
                // Only identity/version metadata changes. The payload and its
                // checksum are untouched, so corruption checks alone cannot pass this test.
                bytes[offset] = (bytes[offset].toInt() xor 1).toByte()
                writeBytes(bytes)
            }
        }
        advance(handle, 12)
        for (rejected in tampered) assertRejectedWithoutMutation(handle, main, rejected)
        assertTrue("Valid state must still load after rejected metadata", NativeCore.loadState(handle, main.stateFile.absolutePath))
    }

    private fun assertRejectedWithoutMutation(handle: Long, session: GameSession, rejected: File) {
        val beforeRam = NativeCore.readMemory(handle, COUNTER_ADDRESS, 256 * 1024)
        val beforeFiles = fileHashes(session.directory)
        val beforeRom = sha256(rom)
        assertFalse("Invalid state must be rejected: ${rejected.name}", NativeCore.loadState(handle, rejected.absolutePath))
        assertArrayEquals("Rejected load must preserve all EWRAM", beforeRam, NativeCore.readMemory(handle, COUNTER_ADDRESS, 256 * 1024))
        assertEquals("Rejected load must preserve branch files", beforeFiles, fileHashes(session.directory))
        assertEquals("Rejected load must preserve the ROM", beforeRom, sha256(rom))
    }

    private fun assertOpenRejected(romPath: String, savePath: String) {
        val handle = NativeCore.open(romPath, savePath)
        if (handle != 0L) handles += handle // Clean up even if a regression opens it.
        assertEquals("Conflicting ROM/save paths must not open a core", 0L, handle)
    }

    private fun open(cartridge: File, session: GameSession): Long {
        val handle = NativeCore.open(cartridge.absolutePath, session.saveFile.absolutePath)
        assertTrue("NativeCore.open failed for ${cartridge.name}", handle != 0L)
        handles += handle
        return handle
    }

    private fun close(handle: Long) {
        try {
            NativeCore.close(handle)
        } finally {
            handles -= handle
        }
    }

    private data class Sound(val shorts: Int, val nonzero: Boolean)

    private fun advance(handle: Long, frames: Int, keys: Int = 0): Sound {
        val audio = ShortArray(4096)
        var total = 0
        var nonzero = false
        repeat(frames) {
            NativeCore.runFrame(handle, keys)
            val count = NativeCore.drainAudio(handle, audio)
            assertTrue("PCM count must fit the output array", count in 0..audio.size)
            assertEquals("PCM must be interleaved stereo", 0, count % 2)
            total += count
            if ((0 until count).any { audio[it] != 0.toShort() }) nonzero = true
        }
        return Sound(total, nonzero)
    }

    private fun assertFrame(handle: Long, pixels: IntArray, color: Int) {
        assertTrue("A completed frame must be available", NativeCore.copyFrame(handle, pixels))
        val mismatch = pixels.indexOfFirst { it != color }
        assertEquals(
            "Expected uniform ARGB ${Integer.toHexString(color)}; first different pixel " +
                "$mismatch is ${pixels.getOrNull(mismatch)?.let(Integer::toHexString)}",
            -1,
            mismatch,
        )
    }

    private fun counter(handle: Long): Long = unsignedWord(NativeCore.readMemory(handle, COUNTER_ADDRESS, 4))
    private fun keys(handle: Long): Int = unsignedWord(NativeCore.readMemory(handle, COUNTER_ADDRESS + 4, 4)).toInt()

    private fun assertBatteryCounter(save: File, expectedCounter: Long) {
        val bytes = save.readBytes()
        assertEquals("Diagnostic SRAM must contain 32 KiB; regenerate and deploy the latest smoke ROM", 32768, bytes.size)
        assertEquals("The diagnostic writes its loop counter to SRAM byte 0", (expectedCounter and 0xFF).toInt(), bytes[0].toInt() and 0xFF)
    }

    private fun unsignedWord(bytes: ByteArray): Long =
        bytes.foldIndexed(0L) { index, value, byte -> value or ((byte.toLong() and 0xFF) shl (index * 8)) }

    private fun expectClosed(action: () -> Unit) {
        try {
            action()
            throw AssertionError("Closed or invalid native handle must throw IllegalStateException")
        } catch (_: IllegalStateException) {
            // JNI must reject the token before it can touch released native memory.
        }
    }

    private fun fileHashes(root: File): Map<String, String> = root.walkTopDown().filter { it.isFile }
        .associate { it.relativeTo(root).invariantSeparatorsPath to sha256(it) }.toSortedMap()

    private fun sha256(file: File): String = MessageDigest.getInstance("SHA-256").digest(file.readBytes())
        .joinToString("") { (it.toInt() and 0xFF).toString(16).padStart(2, '0') }

    private fun headerChecksum(bytes: ByteArray): Int =
        (-(0xA0 until 0xBD).sumOf { bytes[it].toInt() and 0xFF } - 0x19) and 0xFF

    private fun <T> onCore(action: () -> T): T = try {
        owner.submit(Callable { action() }).get(30, TimeUnit.SECONDS)
    } catch (failure: ExecutionException) {
        throw failure.cause ?: failure
    }

    private companion object {
        const val WIDTH = 240
        const val HEIGHT = 160
        const val A = 1
        const val COUNTER_ADDRESS = 0x02000000L
        // create_smoke_rom.py uses RGB555 0x1164 / 0x03FF; mGBA expands each
        // channel as (v << 3) | (v >> 2), then the bridge publishes Android ARGB.
        val IDLE_ARGB = 0xFF215A21.toInt()
        val A_ARGB = 0xFFFFFF00.toInt()
    }
}
